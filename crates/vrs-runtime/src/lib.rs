/// Identifiant d'une fenêtre ouverte (une même fenêtre peut avoir plusieurs instances).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct FormId(u64);

/// Que faire quand la fenêtre principale est fermée ?
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum CloseStrategy {
    /// Fermer la fenêtre principale ferme l'application.
    #[default]
    MainFormCloses,
    /// La fenêtre principale est masquée ; l'application se ferme avec la dernière fenêtre.
    LastFormCloses,
}

/// Fonction appelée sur la fenêtre propriétaire quand une fenêtre ouverte par
/// elle se ferme.
type ClosedCallback = Box<dyn FnOnce(&mut dyn Any, Box<dyn Any>, &mut AppContext)>;

struct Window {
    id: FormId,
    /// `None` pendant que la fenêtre est dessinée.
    form: Option<Box<dyn Form>>,
    title: String,
    size: [f32; 2],
    visible: bool,
    modal: bool,
    owner: Option<FormId>,
    loaded: bool,
    on_closed: Option<ClosedCallback>,
}

enum Request {
    Open(Window),
    Close(FormId),
    Hide(FormId),
    Show(FormId),
    Title(FormId, String),
    Size(FormId, [f32; 2]),
}

/// Accès à l'application depuis les gestionnaires d'événements : ouvrir,
/// fermer, masquer des fenêtres, échanger des données, quitter.
///
/// Les demandes (ouvrir, fermer…) sont appliquées à la fin de l'image en cours.
pub struct AppContext {
    egui_ctx: egui::Context,
    current: FormId,
    windows: Vec<Window>,
    requests: Vec<Request>,
    next_id: u64,
    exit: bool,
}

impl AppContext {
    /// Fenêtre en cours (celle dont le gestionnaire s'exécute).
    pub fn current(&self) -> FormId {
        self.current
    }

    fn open(
        &mut self,
        form: Box<dyn Form>,
        modal: bool,
        on_closed: Option<ClosedCallback>,
    ) -> FormId {
        self.next_id += 1;
        let id = FormId(self.next_id);
        self.requests.push(Request::Open(Window {
            id,
            title: form.title(),
            size: form.size(),
            form: Some(form),
            visible: true,
            modal,
            owner: Some(self.current),
            loaded: false,
            on_closed,
        }));
        id
    }

    fn callback<O: Form, F: Form>(
        then: impl FnOnce(&mut O, F, &mut AppContext) + 'static,
    ) -> ClosedCallback {
        Box::new(
            move |owner: &mut dyn Any, closed: Box<dyn Any>, app: &mut AppContext| {
                if let (Some(owner), Ok(closed)) =
                    (owner.downcast_mut::<O>(), closed.downcast::<F>())
                {
                    then(owner, *closed, app);
                }
            },
        )
    }

    /// Ouvre une nouvelle fenêtre : `app.show_form(Form2::default());`
    pub fn show_form<F: Form>(&mut self, form: F) -> FormId {
        self.open(Box::new(form), false, None)
    }

    /// Ouvre une fenêtre et appelle `then` quand elle se ferme, avec la fenêtre
    /// propriétaire et la fenêtre fermée (pour récupérer ses données).
    pub fn show_form_then<O: Form, F: Form>(
        &mut self,
        form: F,
        then: impl FnOnce(&mut O, F, &mut AppContext) + 'static,
    ) -> FormId {
        self.open(Box::new(form), false, Some(Self::callback(then)))
    }

    /// Ouvre une fenêtre modale : les autres fenêtres sont désactivées tant
    /// qu'elle est ouverte.
    pub fn show_dialog<F: Form>(&mut self, form: F) -> FormId {
        self.open(Box::new(form), true, None)
    }

    /// Ouvre une fenêtre modale et appelle `then` à sa fermeture :
    ///
    /// ```ignore
    /// app.show_dialog_then(Form2::default(), |me: &mut Form1, f2: Form2, _app| {
    ///     me.text_box1.text = f2.text_box1.text;
    /// });
    /// ```
    pub fn show_dialog_then<O: Form, F: Form>(
        &mut self,
        form: F,
        then: impl FnOnce(&mut O, F, &mut AppContext) + 'static,
    ) -> FormId {
        self.open(Box::new(form), true, Some(Self::callback(then)))
    }

    /// Affiche une boîte de message modale avec un bouton OK (MsgBox en VB.NET).
    pub fn message_box(&mut self, text: impl Into<String>) -> FormId {
        let title = self
            .windows
            .iter()
            .find(|w| w.id == self.current)
            .map(|w| w.title.clone())
            .unwrap_or_default();
        self.message_box_titled(title, text)
    }

    /// Boîte de message avec un titre.
    pub fn message_box_titled(
        &mut self,
        title: impl Into<String>,
        text: impl Into<String>,
    ) -> FormId {
        self.show_dialog(MessageBoxForm {
            title: title.into(),
            text: text.into(),
        })
    }

    /// Ferme la fenêtre en cours.
    pub fn close(&mut self) {
        self.requests.push(Request::Close(self.current));
    }

    /// Ferme une fenêtre.
    pub fn close_form(&mut self, id: FormId) {
        self.requests.push(Request::Close(id));
    }

    /// Masque la fenêtre en cours (elle garde son état).
    pub fn hide(&mut self) {
        self.requests.push(Request::Hide(self.current));
    }

    /// Masque une fenêtre.
    pub fn hide_form(&mut self, id: FormId) {
        self.requests.push(Request::Hide(id));
    }

    /// Affiche de nouveau une fenêtre masquée.
    pub fn show_hidden(&mut self, id: FormId) {
        self.requests.push(Request::Show(id));
    }

    /// La fenêtre est-elle ouverte (affichée ou masquée) ?
    pub fn is_open(&self, id: FormId) -> bool {
        id == self.current || self.windows.iter().any(|w| w.id == id)
    }

    /// La fenêtre est-elle affichée ?
    pub fn is_visible(&self, id: FormId) -> bool {
        id == self.current || self.windows.iter().any(|w| w.id == id && w.visible)
    }

    /// Nombre de fenêtres ouvertes.
    pub fn open_forms(&self) -> usize {
        self.windows.len()
    }

    /// Accède à une autre fenêtre ouverte, de type `F`, pour lire ou modifier
    /// ses contrôles. Retourne `None` si elle n'existe pas (ou si c'est la
    /// fenêtre en cours : utilisez alors `self`).
    pub fn with_form<F: Form, R>(&mut self, id: FormId, f: impl FnOnce(&mut F) -> R) -> Option<R> {
        let w = self.windows.iter_mut().find(|w| w.id == id)?;
        let form: &mut dyn Form = w.form.as_deref_mut()?;
        let any: &mut dyn Any = form;
        any.downcast_mut::<F>().map(f)
    }

    /// Change le titre de la fenêtre en cours.
    pub fn set_title(&mut self, title: impl Into<String>) {
        self.requests
            .push(Request::Title(self.current, title.into()));
    }

    /// Change la taille de la fenêtre en cours.
    pub fn set_size(&mut self, width: f32, height: f32) {
        self.requests
            .push(Request::Size(self.current, [width, height]));
    }

    /// Ferme l'application.
    pub fn exit(&mut self) {
        self.exit = true;
    }

    /// Contexte egui, pour les usages avancés (repaint, styles…).
    pub fn egui_ctx(&self) -> &egui::Context {
        &self.egui_ctx
    }
}

/// Fenêtre d'une application VRS. Implémenté par le code généré.
pub trait Form: Any {
    /// Titre initial.
    fn title(&self) -> String;
    /// Taille initiale de la zone cliente (largeur, hauteur).
    fn size(&self) -> [f32; 2];
    /// Dessine la fenêtre et déclenche les gestionnaires d'événements.
    fn show(&mut self, ui: &mut egui::Ui, app: &mut AppContext);
    /// Appelé une fois, avant le premier affichage (événement Load).
    fn load(&mut self, app: &mut AppContext) {
        let _ = app;
    }
    /// Appelé quand l'utilisateur ferme la fenêtre (événement Closing).
    /// Retourner `false` annule la fermeture.
    fn closing(&mut self, app: &mut AppContext) -> bool {
        let _ = app;
        true
    }
    /// Appelé après la fermeture (événement Closed).
    fn closed(&mut self, app: &mut AppContext) {
        let _ = app;
    }
}

/// Gestionnaire central des fenêtres.
struct Runner {
    windows: Vec<Window>,
    requests: Vec<Request>,
    next_id: u64,
    root: FormId,
    strategy: CloseStrategy,
    exiting: bool,
    root_title: String,
}

fn viewport_id(id: FormId) -> egui::ViewportId {
    egui::ViewportId::from_hash_of(("vrs-form", id.0))
}

impl Runner {
    fn new(form: Box<dyn Form>, strategy: CloseStrategy) -> Self {
        let root = FormId(1);
        Self {
            root_title: form.title(),
            windows: vec![Window {
                id: root,
                title: form.title(),
                size: form.size(),
                form: Some(form),
                visible: true,
                modal: false,
                owner: None,
                loaded: false,
                on_closed: None,
            }],
            requests: Vec::new(),
            next_id: 1,
            root,
            strategy,
            exiting: false,
        }
    }

    /// Exécute `f` sur une fenêtre, avec un [`AppContext`] qui donne accès aux autres.
    fn with_form<R>(
        &mut self,
        ctx: &egui::Context,
        id: FormId,
        f: impl FnOnce(&mut dyn Form, &mut AppContext) -> R,
    ) -> Option<R> {
        let idx = self.windows.iter().position(|w| w.id == id)?;
        let mut form = self.windows[idx].form.take()?;
        let mut app = AppContext {
            egui_ctx: ctx.clone(),
            current: id,
            windows: std::mem::take(&mut self.windows),
            requests: std::mem::take(&mut self.requests),
            next_id: self.next_id,
            exit: false,
        };
        let r = f(form.as_mut(), &mut app);
        self.windows = app.windows;
        self.requests = app.requests;
        self.next_id = app.next_id;
        if app.exit {
            self.exit(ctx);
        }
        if let Some(w) = self.windows.iter_mut().find(|w| w.id == id) {
            w.form = Some(form);
        }
        Some(r)
    }

    /// Une fenêtre est bloquée si une fenêtre modale ouverte après elle est affichée.
    fn blocked_by(&self, id: FormId) -> Option<FormId> {
        self.windows
            .iter()
            .filter(|w| w.modal && w.visible && w.id > id)
            .map(|w| w.id)
            .max()
    }

    /// Dessine une fenêtre dans `ui` (zone cliente sans marge).
    fn draw(&mut self, ctx: &egui::Context, id: FormId, ui: &mut egui::Ui) {
        let blocker = self.blocked_by(id);
        self.with_form(ctx, id, |form, app| {
            if let Some(w) = app.windows.iter_mut().find(|w| w.id == id)
                && !w.loaded
            {
                w.loaded = true;
                form.load(app);
            }
            if blocker.is_some() {
                ui.disable();
            }
            form.show(ui, app);
        });
        if let Some(modal) = blocker
            && ui.input(|i| i.pointer.any_click())
        {
            ctx.send_viewport_cmd_to(viewport_id(modal), egui::ViewportCommand::Focus);
        }
    }

    /// L'utilisateur demande la fermeture d'une fenêtre (bouton ✕).
    /// Retourne `true` si la fermeture est acceptée.
    fn user_close(&mut self, ctx: &egui::Context, id: FormId) -> bool {
        if self.exiting {
            return true;
        }
        if self.blocked_by(id).is_some() {
            return false;
        }
        let accepted = self
            .with_form(ctx, id, |form, app| form.closing(app))
            .unwrap_or(true);
        if accepted {
            self.requests.push(Request::Close(id));
        }
        accepted
    }

    fn exit(&mut self, ctx: &egui::Context) {
        self.exiting = true;
        ctx.send_viewport_cmd_to(egui::ViewportId::ROOT, egui::ViewportCommand::Close);
    }

    fn root_visible(&self) -> bool {
        self.windows.iter().any(|w| w.id == self.root && w.visible)
    }

    /// Applique les demandes accumulées (ouvertures, fermetures…).
    fn process_requests(&mut self, ctx: &egui::Context) {
        for _ in 0..64 {
            if self.requests.is_empty() {
                break;
            }
            let requests = std::mem::take(&mut self.requests);
            for r in requests {
                match r {
                    Request::Open(w) => self.windows.push(w),
                    Request::Close(id) => self.close(ctx, id),
                    Request::Hide(id) | Request::Show(id) => {
                        let show = matches!(r, Request::Show(_));
                        if let Some(w) = self.windows.iter_mut().find(|w| w.id == id) {
                            w.visible = show;
                        }
                        if id == self.root {
                            ctx.send_viewport_cmd_to(
                                egui::ViewportId::ROOT,
                                egui::ViewportCommand::Visible(show),
                            );
                        }
                    }
                    Request::Title(id, t) => {
                        if let Some(w) = self.windows.iter_mut().find(|w| w.id == id) {
                            w.title = t.clone();
                        }
                        if id == self.root {
                            self.root_title = t.clone();
                            ctx.send_viewport_cmd_to(
                                egui::ViewportId::ROOT,
                                egui::ViewportCommand::Title(t),
                            );
                        }
                    }
                    Request::Size(id, s) => {
                        if let Some(w) = self.windows.iter_mut().find(|w| w.id == id) {
                            w.size = s;
                        }
                        let vp = if id == self.root {
                            egui::ViewportId::ROOT
                        } else {
                            viewport_id(id)
                        };
                        ctx.send_viewport_cmd_to(vp, egui::ViewportCommand::InnerSize(s.into()));
                    }
                }
            }
        }
    }

    fn close(&mut self, ctx: &egui::Context, id: FormId) {
        if id == self.root {
            let others = self.windows.iter().any(|w| w.id != self.root);
            if self.strategy == CloseStrategy::LastFormCloses && others {
                if let Some(w) = self.windows.iter_mut().find(|w| w.id == id) {
                    w.visible = false;
                }
                ctx.send_viewport_cmd_to(
                    egui::ViewportId::ROOT,
                    egui::ViewportCommand::Visible(false),
                );
                return;
            }
            self.with_form(ctx, id, |form, app| form.closed(app));
            self.exit(ctx);
            return;
        }
        self.with_form(ctx, id, |form, app| form.closed(app));
        let Some(idx) = self.windows.iter().position(|w| w.id == id) else {
            return;
        };
        let mut w = self.windows.remove(idx);
        // Les fenêtres ouvertes par celle-ci restent ouvertes, sans propriétaire.
        for other in &mut self.windows {
            if other.owner == Some(id) {
                other.owner = None;
                other.on_closed = None;
            }
        }
        if let (Some(cb), Some(owner), Some(form)) = (w.on_closed.take(), w.owner, w.form.take()) {
            let closed: Box<dyn Any> = form;
            self.with_form(ctx, owner, |owner_form, app| {
                let owner_any: &mut dyn Any = owner_form;
                cb(owner_any, closed, app);
            });
        }
        // Dernière fenêtre fermée alors que la fenêtre principale est masquée.
        if self.strategy == CloseStrategy::LastFormCloses
            && !self.root_visible()
            && self.windows.iter().all(|w| w.id == self.root)
        {
            self.with_form(ctx, self.root, |form, app| form.closed(app));
            self.exit(ctx);
        }
    }

    /// Une image : fenêtre principale, puis fenêtres secondaires.
    fn frame(&mut self, ui: &mut egui::Ui) {
        let ctx = ui.ctx().clone();
        if ctx.input(|i| i.viewport().close_requested()) && !self.exiting {
            let root = self.root;
            let others = self.windows.iter().any(|w| w.id != root);
            if !self.user_close(&ctx, root)
                || (self.strategy == CloseStrategy::LastFormCloses && others)
            {
                ctx.send_viewport_cmd(egui::ViewportCommand::CancelClose);
            }
        }

        let frame = egui::Frame::central_panel(ui.style()).inner_margin(0.0);
        let root = self.root;
        egui::CentralPanel::default_margins()
            .frame(frame)
            .show(ui, |ui| self.draw(&ctx, root, ui));

        let others: Vec<(FormId, String, [f32; 2])> = self
            .windows
            .iter()
            .filter(|w| w.id != root && w.visible)
            .map(|w| (w.id, w.title.clone(), w.size))
            .collect();
        for (id, title, size) in others {
            let builder = egui::ViewportBuilder::default()
                .with_title(title)
                .with_inner_size(size);
            ctx.clone()
                .show_viewport_immediate(viewport_id(id), builder, |ui, class| {
                    if ui.input(|i| i.viewport().close_requested()) && !self.user_close(&ctx, id) {
                        ui.ctx()
                            .send_viewport_cmd(egui::ViewportCommand::CancelClose);
                    }
                    if class == egui::ViewportClass::EmbeddedWindow {
                        // Pas de fenêtres natives multiples : sous-fenêtre egui.
                        ui.set_min_size(size.into());
                        egui::Frame::NONE.show(ui, |ui| {
                            ui.set_min_size(size.into());
                            self.draw(&ctx, id, ui);
                        });
                    } else {
                        let frame = egui::Frame::central_panel(ui.style()).inner_margin(0.0);
                        egui::CentralPanel::default_margins()
                            .frame(frame)
                            .show(ui, |ui| self.draw(&ctx, id, ui));
                    }
                });
        }
        self.process_requests(&ctx);
    }
}

impl eframe::App for Runner {
    fn ui(&mut self, ui: &mut egui::Ui, _frame: &mut eframe::Frame) {
        self.frame(ui);
    }
}

/// Démarre l'application avec sa fenêtre principale.
pub fn run<F: Form>(form: F) -> eframe::Result {
    run_with(form, CloseStrategy::MainFormCloses)
}

/// Démarre l'application avec une stratégie de fermeture.
pub fn run_with<F: Form>(form: F, strategy: CloseStrategy) -> eframe::Result {
    let title = form.title();
    let options = eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default()
            .with_title(title.clone())
            .with_inner_size(form.size()),
        ..Default::default()
    };
    eframe::run_native(
        &title,
        options,
        Box::new(move |_cc| Ok(Box::new(Runner::new(Box::new(form), strategy)))),
    )
}

