/// Dessine un contrôle à onglets. `response.changed()` indique un changement de page.
pub fn tab_control(
    ui: &mut egui::Ui,
    id_salt: &str,
    state: &mut TabControlState,
) -> egui::Response {
    if !state.visible {
        return hidden(ui, id_salt);
    }
    let rect = anchored_rect(ui, state.bounds, state.anchor);
    let visuals = ui.visuals().clone();
    let header = 26.0_f32.min(rect.height());
    let body = egui::Rect::from_min_max(rect.min + egui::vec2(0.0, header), rect.max);
    ui.painter().rect(
        body,
        2.0,
        state.back_color.unwrap_or(visuals.panel_fill),
        visuals.widgets.noninteractive.bg_stroke,
        egui::StrokeKind::Inside,
    );
    let before = state.selected;
    let (fore, size) = (state.fore_color, state.font_size);
    let header_rect = egui::Rect::from_min_size(rect.min, egui::vec2(rect.width(), header));
    let pages = &state.pages;
    let selected = &mut state.selected;
    let mut r = ui
        .scope_builder(
            egui::UiBuilder::new()
                .id_salt(id_salt)
                .max_rect(header_rect)
                .layout(egui::Layout::left_to_right(egui::Align::Center)),
            |ui| {
                if !state.enabled {
                    ui.disable();
                }
                for (i, p) in pages.iter().enumerate() {
                    if ui
                        .selectable_label(*selected == i, rich(p, fore, size))
                        .clicked()
                    {
                        *selected = i;
                    }
                }
            },
        )
        .response;
    if state.selected != before {
        r.mark_changed();
    }
    with_tooltip(r, &state.tooltip)
}

/// Fait avancer une minuterie. `response.changed()` indique un Tick.
pub fn timer(ui: &mut egui::Ui, id_salt: &str, state: &mut TimerState) -> egui::Response {
    let mut r = hidden(ui, id_salt);
    if !state.enabled {
        state.last_tick = None;
        return r;
    }
    let now = ui.input(|i| i.time);
    let interval = f64::from(state.interval_ms.max(1)) / 1000.0;
    match state.last_tick {
        None => state.last_tick = Some(now),
        Some(t) if now - t >= interval => {
            state.last_tick = Some(now);
            r.mark_changed();
        }
        Some(_) => {}
    }
    let remaining = state
        .last_tick
        .map_or(interval, |t| (t + interval - now).max(0.0));
    ui.ctx()
        .request_repaint_after(std::time::Duration::from_secs_f64(remaining));
    r
}

