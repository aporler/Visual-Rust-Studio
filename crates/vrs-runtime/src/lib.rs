#![allow(dead_code)]

pub use eframe;
pub use eframe::egui;

/// Position et taille d'un contrôle, en points, relatives au coin supérieur
/// gauche de la zone cliente de la fenêtre.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Bounds {
    pub x: f32,
    pub y: f32,
    pub width: f32,
    pub height: f32,
}

impl Bounds {
    /// Crée un rectangle.
    pub const fn new(x: f32, y: f32, width: f32, height: f32) -> Self {
        Self {
            x,
            y,
            width,
            height,
        }
    }

    /// Rectangle à l'écran, à partir de l'origine de la zone cliente.
    pub fn to_rect(self, origin: egui::Pos2) -> egui::Rect {
        egui::Rect::from_min_size(
            origin + egui::vec2(self.x, self.y),
            egui::vec2(self.width.max(1.0), self.height.max(1.0)),
        )
    }
}

/// État d'un bouton (équivalent de `Button` en Windows Forms).
#[derive(Clone, Debug, PartialEq)]
pub struct ButtonState {
    pub text: String,
    pub bounds: Bounds,
    pub visible: bool,
    pub enabled: bool,
    pub tooltip: String,
}

/// État d'une étiquette (`Label`).
#[derive(Clone, Debug, PartialEq)]
pub struct LabelState {
    pub text: String,
    pub bounds: Bounds,
    pub visible: bool,
    pub enabled: bool,
    pub tooltip: String,
}

/// État d'une zone de texte (`TextBox`).
#[derive(Clone, Debug, PartialEq)]
pub struct TextBoxState {
    pub text: String,
    pub bounds: Bounds,
    pub visible: bool,
    pub enabled: bool,
    pub tooltip: String,
}

macro_rules! impl_state_new {
    ($($t:ident),*) => {$(
        impl $t {
            /// Nouvel état visible et activé.
            pub fn new(text: impl Into<String>, bounds: Bounds) -> Self {
                Self {
                    text: text.into(),
                    bounds,
                    visible: true,
                    enabled: true,
                    tooltip: String::new(),
                }
            }
        }
    )*};
}
impl_state_new!(ButtonState, LabelState, TextBoxState);

/// Dessine un contenu dans le rectangle `bounds`, avec l'état activé/désactivé.
fn place(
    ui: &mut egui::Ui,
    id_salt: &str,
    bounds: Bounds,
    enabled: bool,
    layout: egui::Layout,
    add: impl FnOnce(&mut egui::Ui) -> egui::Response,
) -> egui::Response {
    let rect = bounds.to_rect(ui.max_rect().min);
    ui.scope_builder(
        egui::UiBuilder::new()
            .id_salt(id_salt)
            .max_rect(rect)
            .layout(layout),
        |ui| {
            ui.set_clip_rect(rect.intersect(ui.clip_rect()));
            if !enabled {
                ui.disable();
            }
            add(ui)
        },
    )
    .inner
}

/// Réponse vide pour un contrôle masqué (jamais cliqué, jamais modifié).
fn hidden(ui: &mut egui::Ui, id_salt: &str) -> egui::Response {
    ui.interact(
        egui::Rect::NOTHING,
        ui.scope_id().with(id_salt),
        egui::Sense::hover(),
    )
}

fn with_tooltip(response: egui::Response, tooltip: &str) -> egui::Response {
    if tooltip.is_empty() {
        response
    } else {
        response
            .on_hover_text(tooltip)
            .on_disabled_hover_text(tooltip)
    }
}

/// Dessine un bouton. `response.clicked()` indique un clic.
pub fn button(ui: &mut egui::Ui, id_salt: &str, state: &ButtonState) -> egui::Response {
    if !state.visible {
        return hidden(ui, id_salt);
    }
    let r = place(
        ui,
        id_salt,
        state.bounds,
        state.enabled,
        egui::Layout::centered_and_justified(egui::Direction::TopDown),
        |ui| ui.add(egui::Button::new(state.text.as_str())),
    );
    with_tooltip(r, &state.tooltip)
}

/// Dessine une étiquette. `response.clicked()` indique un clic.
pub fn label(ui: &mut egui::Ui, id_salt: &str, state: &LabelState) -> egui::Response {
    if !state.visible {
        return hidden(ui, id_salt);
    }
    let r = place(
        ui,
        id_salt,
        state.bounds,
        state.enabled,
        egui::Layout::left_to_right(egui::Align::Center),
        |ui| {
            ui.add(
                egui::Label::new(state.text.as_str())
                    .selectable(false)
                    .sense(egui::Sense::click()),
            )
        },
    );
    with_tooltip(r, &state.tooltip)
}

/// Dessine une zone de texte modifiable. `response.changed()` indique une saisie.
pub fn text_box(ui: &mut egui::Ui, id_salt: &str, state: &mut TextBoxState) -> egui::Response {
    if !state.visible {
        return hidden(ui, id_salt);
    }
    let TextBoxState {
        text,
        bounds,
        enabled,
        tooltip,
        ..
    } = state;
    let r = place(
        ui,
        id_salt,
        *bounds,
        *enabled,
        egui::Layout::centered_and_justified(egui::Direction::TopDown),
        |ui| {
            ui.add(
                egui::TextEdit::singleline(text)
                    .id_salt(id_salt)
                    .desired_width(f32::INFINITY),
            )
        },
    );
    with_tooltip(r, tooltip)
}

/// Accès à l'application depuis les gestionnaires d'événements.
///
/// N'expose que des opérations réellement implémentées. L'ouverture d'autres
/// fenêtres (Form2…) sera ajoutée dans une version ultérieure.
pub struct AppContext {
    egui_ctx: egui::Context,
    title: Option<String>,
    exit: bool,
}

impl AppContext {
    fn new(egui_ctx: egui::Context) -> Self {
        Self {
            egui_ctx,
            title: None,
            exit: false,
        }
    }

    /// Change le titre de la fenêtre.
    pub fn set_title(&mut self, title: impl Into<String>) {
        self.title = Some(title.into());
    }

    /// Ferme l'application.
    pub fn exit(&mut self) {
        self.exit = true;
    }

    /// Contexte egui, pour les usages avancés (repaint, styles…).
    pub fn egui_ctx(&self) -> &egui::Context {
        &self.egui_ctx
    }
}

/// Fenêtre d'une application VRS. Implémenté par le code généré.
pub trait Form {
    /// Titre initial.
    fn title(&self) -> String;
    /// Taille initiale de la zone cliente (largeur, hauteur).
    fn size(&self) -> [f32; 2];
    /// Dessine la fenêtre et déclenche les gestionnaires d'événements.
    fn show(&mut self, ui: &mut egui::Ui, app: &mut AppContext);
    /// Appelé une fois, avant le premier affichage (événement Load).
    fn load(&mut self, app: &mut AppContext) {
        let _ = app;
    }
}

struct Runner<F: Form> {
    form: F,
    loaded: bool,
}

impl<F: Form> Runner<F> {
    /// Exécute une image : chargement éventuel, dessin, commandes de fenêtre.
    fn frame(&mut self, ui: &mut egui::Ui) {
        let mut app = AppContext::new(ui.ctx().clone());
        if !self.loaded {
            self.loaded = true;
            self.form.load(&mut app);
        }
        let frame = egui::Frame::central_panel(ui.style()).inner_margin(0.0);
        egui::CentralPanel::default_margins()
            .frame(frame)
            .show(ui, |ui| self.form.show(ui, &mut app));
        if let Some(title) = app.title.take() {
            ui.ctx()
                .send_viewport_cmd(egui::ViewportCommand::Title(title));
        }
        if app.exit {
            ui.ctx().send_viewport_cmd(egui::ViewportCommand::Close);
        }
    }
}

impl<F: Form> eframe::App for Runner<F> {
    fn ui(&mut self, ui: &mut egui::Ui, _frame: &mut eframe::Frame) {
        self.frame(ui);
    }
}

/// Démarre l'application avec sa fenêtre principale.
pub fn run<F: Form + 'static>(form: F) -> eframe::Result {
    let title = form.title();
    let options = eframe::NativeOptions {
        viewport: egui::ViewportBuilder::default()
            .with_title(title.clone())
            .with_inner_size(form.size()),
        ..Default::default()
    };
    eframe::run_native(
        &title,
        options,
        Box::new(|_cc| {
            Ok(Box::new(Runner {
                form,
                loaded: false,
            }))
        }),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Fenêtre écrite à la main comme le ferait le générateur de code.
    struct Demo {
        button1: ButtonState,
        text_box1: TextBoxState,
        loads: u32,
    }

    impl Form for Demo {
        fn title(&self) -> String {
            "Demo".into()
        }
        fn size(&self) -> [f32; 2] {
            [300.0, 200.0]
        }
        fn show(&mut self, ui: &mut egui::Ui, app: &mut AppContext) {
            let button1 = button(ui, "button1", &self.button1);
            let _ = text_box(ui, "text_box1", &mut self.text_box1);
            if button1.clicked() {
                self.text_box1.text = "Bonjour !".into();
                app.set_title("Cliqué");
            }
        }
        fn load(&mut self, _app: &mut AppContext) {
            self.loads += 1;
        }
    }

    #[test]
    fn click_updates_text_box() {
        use egui_kittest::kittest::Queryable;
        let mut runner = Runner {
            form: Demo {
                button1: ButtonState::new("OK", Bounds::new(10.0, 10.0, 80.0, 28.0)),
                text_box1: TextBoxState::new("", Bounds::new(10.0, 50.0, 150.0, 24.0)),
                loads: 0,
            },
            loaded: false,
        };
        // Les zones de texte générées n'ont pas encore de nom accessible (étiquette associée).
        let mut harness = egui_kittest::Harness::builder()
            .with_accessibility_check(false)
            .build_ui_state(|ui, runner: &mut Runner<Demo>| runner.frame(ui), runner);
        harness.run();
        harness.get_by_label("OK").click();
        harness.run();
        runner = harness.into_state();
        assert_eq!(runner.form.text_box1.text, "Bonjour !");
        assert_eq!(runner.form.loads, 1);
    }

    #[test]
    fn hidden_control_is_not_clickable() {
        use egui_kittest::kittest::Queryable;
        let mut b = ButtonState::new("Caché", Bounds::new(0.0, 0.0, 50.0, 20.0));
        b.visible = false;
        let harness = egui_kittest::Harness::new_ui(move |ui| {
            let _ = button(ui, "b", &b);
        });
        assert!(harness.query_by_label("Caché").is_none());
    }
}
