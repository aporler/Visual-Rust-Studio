//! Génération de code Rust pour les projets graphiques de Visual Rust Studio.
//!
//! Pour chaque fenêtre `FormN`, deux fichiers Rust existent :
//!
//! | Fichier                         | Propriétaire | Régénéré ? |
//! |---------------------------------|--------------|------------|
//! | `src/forms/formn_designer.rs`   | VRS          | oui, à chaque modification du concepteur |
//! | `src/forms/formn.rs`            | utilisateur  | **jamais** : VRS n'y ajoute que les gestionnaires manquants |
//!
//! S'y ajoutent `src/forms/mod.rs` (généré) et `src/vrs/mod.rs` (copie du runtime).
//! `src/main.rs` est créé une seule fois et appartient ensuite à l'utilisateur.
//!
//! Le code généré est du Rust standard, mis en forme par `prettyplease`.

mod designer;
mod user_code;

use std::path::{Path, PathBuf};

use vrs_components::FormDocument;

pub use designer::{generate_designer, generate_forms_mod, uses_images};
pub use user_code::{
    ensure_data_struct, ensure_handler, ensure_handler_returning, find_fn_line, user_file_skeleton,
};

/// Source du runtime copié dans `src/vrs/mod.rs`.
pub const RUNTIME_SOURCE: &str = include_str!("../../vrs-runtime/src/lib.rs");

/// Version d'eframe utilisée par les projets générés (identique à celle de VRS).
pub const EFRAME_VERSION: &str = "0.37";

/// En-tête des fichiers entièrement générés.
pub fn generated_header(source: &str) -> String {
    format!(
        "// ---------------------------------------------------------------------------\n\
         // <auto-generated> Visual Rust Studio\n\
         // Ce fichier est régénéré automatiquement : ne le modifiez pas à la main.\n\
         // This file is regenerated automatically: do not edit it by hand.\n\
         // Source : {source}\n\
         // ---------------------------------------------------------------------------\n\n"
    )
}

/// Textes insérés dans le code de l'utilisateur (traduits par l'IDE).
pub trait Comments {
    /// Documentation d'un gestionnaire (« Gère l'événement Click de `button1`. »).
    fn handler_doc(&self, event: &str, owner: &str) -> String;
    /// Commentaire placé dans le corps d'un nouveau gestionnaire.
    fn todo(&self) -> String;
    /// Documentation du fichier de code d'une fenêtre.
    fn user_file_doc(&self, form: &str) -> String;
    /// Documentation de la structure des variables de la fenêtre.
    fn data_doc(&self) -> String {
        "Variables of this window (like the variables declared in a VB.NET form). \
         Add your fields here and use them with `self.data`."
            .into()
    }
}

/// Textes anglais par défaut.
pub struct EnglishComments;

impl Comments for EnglishComments {
    fn handler_doc(&self, event: &str, owner: &str) -> String {
        format!("Handles the {event} event of `{owner}`.")
    }
    fn todo(&self) -> String {
        "TODO: write your code here.".into()
    }
    fn user_file_doc(&self, form: &str) -> String {
        format!(
            "Code of window {form}. This file belongs to you: Visual Rust Studio only adds \
             new event handlers and never modifies existing code."
        )
    }
}

/// Erreur de génération.
#[derive(Debug)]
pub enum CodegenError {
    /// La fenêtre contient des noms invalides.
    InvalidForm(Vec<String>),
    /// Le fichier de l'utilisateur ne peut pas être analysé (erreur de syntaxe) :
    /// VRS refuse d'y toucher.
    UserCode {
        path: PathBuf,
        message: String,
    },
    Io(std::io::Error),
}

impl std::fmt::Display for CodegenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::InvalidForm(p) => write!(f, "{}", p.join(" ; ")),
            Self::UserCode { path, message } => write!(
                f,
                "{} contient une erreur de syntaxe ; aucun gestionnaire n'a été ajouté : {message}",
                path.display()
            ),
            Self::Io(e) => write!(f, "{e}"),
        }
    }
}

impl std::error::Error for CodegenError {}

impl From<std::io::Error> for CodegenError {
    fn from(e: std::io::Error) -> Self {
        Self::Io(e)
    }
}

/// Résultat d'une synchronisation.
#[derive(Debug, Default)]
pub struct SyncReport {
    /// Fichiers écrits (créés ou modifiés).
    pub written: Vec<PathBuf>,
    /// Gestionnaires ajoutés au code utilisateur.
    pub handlers_added: Vec<String>,
    /// Copies de sauvegarde créées avant de modifier un fichier utilisateur.
    pub backups: Vec<PathBuf>,
}

/// Chemins des fichiers d'une fenêtre.
pub struct FormPaths {
    pub designer: PathBuf,
    pub user: PathBuf,
}

/// Chemins des fichiers Rust d'une fenêtre dans un projet.
pub fn form_paths(root: &Path, form_name: &str) -> FormPaths {
    let module = vrs_core::ident::to_snake_case(form_name);
    let dir = root.join("src").join("forms");
    FormPaths {
        designer: dir.join(format!("{module}_designer.rs")),
        user: dir.join(format!("{module}.rs")),
    }
}

/// Régénère tout le code d'un projet graphique.
///
/// - `src/vrs/mod.rs` : runtime ;
/// - `src/forms/mod.rs` : liste des fenêtres et fenêtre de démarrage ;
/// - pour chaque fenêtre : fichier du concepteur, fichier utilisateur (créé s'il
///   n'existe pas) et gestionnaires manquants.
pub fn sync_project(
    root: &Path,
    forms: &[FormDocument],
    startup: &str,
    last_form_closes: bool,
    comments: &dyn Comments,
) -> Result<SyncReport, CodegenError> {
    let mut report = SyncReport::default();
    for form in forms {
        let problems = form.validate();
        if !problems.is_empty() {
            return Err(CodegenError::InvalidForm(problems));
        }
    }

    if forms.iter().any(uses_images) {
        ensure_image_dependencies(root, &mut report)?;
    }

    let runtime_path = root.join("src").join("vrs").join("mod.rs");
    let runtime = format!(
        "{}{RUNTIME_SOURCE}",
        generated_header("Visual Rust Studio (vrs-runtime)")
    );
    if vrs_core::fs::write_if_changed(&runtime_path, &runtime)? {
        report.written.push(runtime_path);
    }

    let mod_path = root.join("src").join("forms").join("mod.rs");
    let mod_src = generate_forms_mod(forms, startup, last_form_closes);
    if vrs_core::fs::write_if_changed(&mod_path, &mod_src)? {
        report.written.push(mod_path);
    }

    for form in forms {
        sync_form_into(root, form, comments, &mut report)?;
    }
    Ok(report)
}

/// Dépendances nécessaires pour afficher des images (PictureBox).
pub const IMAGE_DEPENDENCIES: &str = "egui_extras = { version = \"0.37\", features = [\"image\"] }\nimage = { version = \"0.25\", default-features = false, features = [\"png\", \"jpeg\", \"gif\", \"bmp\"] }\n";

/// Ajoute `egui_extras` et `image` au `Cargo.toml` s'ils sont absents
/// (copie `.bak` avant modification ; le reste du fichier n'est pas touché).
fn ensure_image_dependencies(root: &Path, report: &mut SyncReport) -> Result<(), CodegenError> {
    let manifest = root.join("Cargo.toml");
    let text = std::fs::read_to_string(&manifest)?;
    let has = |name: &str| {
        text.lines()
            .any(|l| l.trim_start().starts_with(name) && l.contains('='))
    };
    let mut missing = String::new();
    for line in IMAGE_DEPENDENCIES.lines() {
        let name = line.split_whitespace().next().unwrap_or_default();
        if !has(name) {
            missing.push_str(line);
            missing.push('\n');
        }
    }
    if missing.is_empty() {
        return Ok(());
    }
    let new_text = match text.find("[dependencies]") {
        Some(i) => {
            let after = i + "[dependencies]".len();
            let line_end = text[after..]
                .find('\n')
                .map_or(text.len(), |j| after + j + 1);
            format!("{}{missing}{}", &text[..line_end], &text[line_end..])
        }
        None => format!("{}\n[dependencies]\n{missing}", text.trim_end()),
    };
    if let Some(bak) = vrs_core::fs::backup_file(&manifest)? {
        report.backups.push(bak);
    }
    vrs_core::fs::atomic_write(&manifest, new_text)?;
    report.written.push(manifest);
    Ok(())
}

/// Régénère le code d'une seule fenêtre.
pub fn sync_form(
    root: &Path,
    form: &FormDocument,
    comments: &dyn Comments,
) -> Result<SyncReport, CodegenError> {
    let problems = form.validate();
    if !problems.is_empty() {
        return Err(CodegenError::InvalidForm(problems));
    }
    let mut report = SyncReport::default();
    sync_form_into(root, form, comments, &mut report)?;
    Ok(report)
}

fn sync_form_into(
    root: &Path,
    form: &FormDocument,
    comments: &dyn Comments,
    report: &mut SyncReport,
) -> Result<(), CodegenError> {
    let paths = form_paths(root, &form.name);
    let designer = generate_designer(form);
    if vrs_core::fs::write_if_changed(&paths.designer, &designer)? {
        report.written.push(paths.designer.clone());
    }

    let original = match std::fs::read_to_string(&paths.user) {
        Ok(s) => Some(s),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(e.into()),
    };
    let mut src = original
        .clone()
        .unwrap_or_else(|| user_file_skeleton(form, comments));
    // Structure des variables de la fenêtre (`Form1Data`), ajoutée si absente.
    let mut data_added = false;
    match ensure_data_struct(&src, &form.name, &comments.data_doc()) {
        Ok(Some(updated)) => {
            src = updated;
            data_added = true;
        }
        Ok(None) => {}
        Err(message) => {
            return Err(CodegenError::UserCode {
                path: paths.user.clone(),
                message,
            });
        }
    }
    let mut added = Vec::new();
    for (handler, owner, event) in form.handlers() {
        let owner = owner.unwrap_or_else(|| form.name.clone());
        let doc = comments.handler_doc(event.name(), &owner);
        match ensure_handler_returning(
            &src,
            &form.name,
            &handler,
            &doc,
            &comments.todo(),
            event.handler_return(),
        ) {
            Ok(Some(updated)) => {
                src = updated;
                added.push(handler);
            }
            Ok(None) => {}
            Err(message) => {
                return Err(CodegenError::UserCode {
                    path: paths.user.clone(),
                    message,
                });
            }
        }
    }
    match original {
        None => {
            vrs_core::fs::atomic_write(&paths.user, &src)?;
            report.written.push(paths.user.clone());
        }
        Some(_) if !added.is_empty() || data_added => {
            if let Some(bak) = vrs_core::fs::backup_file(&paths.user)? {
                report.backups.push(bak);
            }
            vrs_core::fs::atomic_write(&paths.user, &src)?;
            report.written.push(paths.user.clone());
        }
        Some(_) => {}
    }
    report.handlers_added.extend(added);
    Ok(())
}
